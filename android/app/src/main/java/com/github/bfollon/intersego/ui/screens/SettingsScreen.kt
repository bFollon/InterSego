package com.github.bfollon.intersego.ui.screens

import androidx.compose.foundation.layout.Column
import androidx.compose.foundation.layout.fillMaxWidth
import androidx.compose.foundation.layout.padding
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.automirrored.filled.ArrowBack
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.unit.dp
import com.github.bfollon.intersego.services.GuidedModePrefs

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun SettingsScreen(
    onBack: () -> Unit
) {
    val context = LocalContext.current
    var guidedModeEnabled by remember {
        mutableStateOf(GuidedModePrefs.isGuidedModeEnabled())
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Configuración") },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Volver")
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = MaterialTheme.colorScheme.primaryContainer,
                    titleContentColor = MaterialTheme.colorScheme.onPrimaryContainer
                )
            )
        }
    ) { innerPadding ->
        LazyColumn(
            modifier = Modifier
                .fillMaxWidth()
                .padding(innerPadding)
        ) {
            item {
                // Guided mode section
                ListItem(
                    headlineContent = { Text("Modo guiado") },
                    supportingContent = { Text("Mostrar selector de dirección antes de ver salidas") },
                    trailingContent = {
                        Switch(
                            checked = guidedModeEnabled,
                            onCheckedChange = { newValue ->
                                guidedModeEnabled = newValue
                                GuidedModePrefs.setGuidedModeEnabled(newValue)
                            }
                        )
                    }
                )
                Divider()
            }
        }
    }
}
